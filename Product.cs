class Product
{
    private string name;
    private double price;
    private supplier supplier;
    public string Name
    {
        get {return name;}
        set {name = value;}
    }
    public double Price
    {
        get {return price;}
        set {price = value;}
    }
    public supplier Supplier
    {
        get {return supplier;}
        set {supplier = value;}
    }
}